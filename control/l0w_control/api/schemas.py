"""API models: the single source of the OpenAPI contract.

The web app's TypeScript types are generated from the spec these produce
(`control/openapi.json`, regenerated by `scripts/export_openapi.py`).
Field names are snake_case on the wire. Times are UTC datetimes.
"""

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


Actor = Literal["owner", "assistant", "chat"]
Sender = Literal["owner", "assistant", "chat", "system"]
Volume = Literal["workspace", "work"]
IdempotencyKey = Annotated[
    str | None,
    Field(default=None, max_length=100, description="Client-generated key; repeating a create with the same key returns the first result."),
]


class Ok(Model):
    ok: Literal[True] = True


# ── Meta, status, sync ─────────────────────────────────────────────────────
class Capabilities(Model):
    hub: bool = False
    push: bool = False
    passkeys: bool = False
    chat: bool = False
    extensions: list[str] = []


class Meta(Model):
    server_version: str
    api_version: str
    ui_bundle_version: str
    capabilities: Capabilities
    setup_complete: bool
    instance_name: str


AssistantState = Literal["working", "asleep", "dormant", "paused"]


class BudgetSummary(Model):
    unit: str = Field(description="Display unit, e.g. 'pts'. See design/mockup/REVIEW.md #10.")
    left: float
    allowance: float
    used_by_assistant: float
    used_by_owner: float
    resets_at: datetime | None = None


class Status(Model):
    state: AssistantState
    now: str | None = Field(None, description="The 'now' sentence while working.")
    run_id: int | None = None
    run_used: float | None = None
    run_budget: float | None = None
    next_wakeup_at: datetime | None = None
    budget: BudgetSummary
    inbox_waiting: int
    reply_budget_left: float | None = None


class SyncChange(Model):
    entity: str
    id: str
    op: Literal["upsert", "delete"]
    data: dict[str, Any] | None = Field(None, description="The entity as its GET endpoint returns it; absent for deletes.")


class SyncResponse(Model):
    cursor: str
    changes: list[SyncChange]
    reset: bool = Field(False, description="True if the cursor was too old: drop the cache and refetch.")


