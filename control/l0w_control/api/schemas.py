"""API models: the single source of the OpenAPI contract.

The web app's TypeScript types are generated from the spec these produce
(`control/openapi.json`, regenerated by `scripts/export_openapi.py`).
Field names are snake_case on the wire. Times are UTC datetimes.
"""

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


